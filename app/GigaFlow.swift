    func installInteractionMonitoring() {
        let events: NSEvent.EventTypeMask = [.keyDown, .leftMouseDown, .rightMouseDown, .otherMouseDown]
        globalInputMonitor = NSEvent.addGlobalMonitorForEvents(matching: events) { [weak self] event in
            self?.trackInteraction(event)
        }
        localInputMonitor = NSEvent.addLocalMonitorForEvents(matching: events) { [weak self] event in
            if let self = self {
                if event.window === self.hud && (event.type == .leftMouseDown || event.type == .rightMouseDown) {
                    self.inputCounterGuard.allowHUDClick(event)
                } else { self.trackInteraction(event) }
            }
            return event
        }
        activationMonitor = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] _ in self?.interactionSerial &+= 1 }
        interactionMonitoringAvailable = globalInputMonitor != nil && localInputMonitor != nil
    }

    func trackInteraction(_ event: NSEvent) {
        // Forward is the dictation command; all other input invalidates window-only fallback.
        if event.type == .otherMouseDown && event.buttonNumber == 4 { return }
        if event.type == .keyDown && DictationShortcut.matches(keyCode: event.keyCode,
            flags: event.modifierFlags, primaryAvailable: primaryHotKey != nil, f18Available: hotKey != nil) { return }
        interactionSerial &+= 1
    }

    func registerHotKey() {
        var specs = [EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed)),
                     EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyReleased))]
        let pointer = Unmanaged.passUnretained(self).toOpaque()
        let installed = InstallEventHandler(GetApplicationEventTarget(), { _, event, context in
            guard let context = context, let event = event else { return OSStatus(eventNotHandledErr) }
            let app = Unmanaged<AppDelegate>.fromOpaque(context).takeUnretainedValue()
            var key = EventHotKeyID(signature: 0, id: 0)
            guard GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID),
                nil, MemoryLayout<EventHotKeyID>.size, nil, &key) == noErr,
                key.signature == 0x4749464C, key.id == 1 || key.id == 2 else { return OSStatus(eventNotHandledErr) }
            let down = GetEventKind(event) == UInt32(kEventHotKeyPressed)
            let identifier = key.id
            DispatchQueue.main.async { app.keyboardTrigger(down: down, identifier: identifier) }
            return noErr
        }, 2, &specs, pointer, &eventHandler)
        guard installed == noErr else { message = "Не удалось подключить горячие клавиши. Используйте меню или Forward."; return }
        let f18ID = EventHotKeyID(signature: 0x4749464C, id: 1)
        let primaryID = EventHotKeyID(signature: 0x4749464C, id: 2)
        let f18 = RegisterEventHotKey(UInt32(kVK_F18), 0, f18ID, GetApplicationEventTarget(), 0, &hotKey)
        let primary = RegisterEventHotKey(UInt32(kVK_Space), UInt32(controlKey | shiftKey), primaryID,
                                          GetApplicationEventTarget(), 0, &primaryHotKey)
        hotkeyAvailable = f18 == noErr || primary == noErr
        if !hotkeyAvailable {
            message = "Горячие клавиши заняты. Используйте меню или Forward через Hammerspoon."
        }
    }

    func keyboardTrigger(down: Bool, identifier: UInt32) {
        triggerCount += 1
        if down {
            if mode == .recording || mode == .processing { inputCounterGuard.allowHotKeyPress() }
            guard heldHotKeys.insert(identifier).inserted else { return }
            toggleRecording()
        } else {
            heldHotKeys.remove(identifier)
        }
    }
    @objc func bridgeStart() { DispatchQueue.main.async { if self.mode == .ready { self.startRecording() } } }
    @objc func bridgeStop() { DispatchQueue.main.async { if self.mode == .recording { self.finishRecording() } } }
    @objc func bridgeToggle() { DispatchQueue.main.async { self.triggerCount += 1; self.toggleRecording() } }
